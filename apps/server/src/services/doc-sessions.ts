import {
  MAX_DOCUMENT_LENGTH,
  RgaDocument,
  diffLines,
  excerpt,
  randomSiteId,
  rgaOpSchema,
  type DocumentDto,
  type RgaOp,
  type TextChange,
} from "@rcp/shared";
import { notFound } from "../core/errors.js";
import { iso } from "../core/util.js";
import type { DocumentRecord } from "../repositories/documents.js";
import type { ActivityService } from "./activity-service.js";
import type { ServiceDeps } from "./context.js";

export interface Participant {
  readonly connectionId: string;
  readonly userId: string;
  /** CRDT site id assigned by the server; ops from this connection must use it. */
  readonly site: string;
  /** Highest server sequence number the client confirmed integrating. */
  ackSeq: number;
}

/** In-memory state of one open document. */
export class DocSession {
  readonly participants = new Map<string, Participant>();
  opsSinceSnapshot = 0;
  contentDirty = false;
  flushTimer: NodeJS.Timeout | null = null;

  constructor(
    public meta: DocumentRecord,
    readonly doc: RgaDocument,
    public headSeq: number,
    public snapshotSeq: number,
    public lastTouched: number,
  ) {}

  get id(): string {
    return this.meta.id;
  }

  get workspaceId(): string {
    return this.meta.workspaceId;
  }

  get text(): string {
    return this.doc.toString();
  }

  /**
   * True when every connected replica has acknowledged the current head, i.e.
   * all replicas hold the same operations. Only then may tombstones be
   * collected (see RgaDocument.collectGarbage).
   */
  isQuiescent(): boolean {
    for (const p of this.participants.values()) if (p.ackSeq < this.headSeq) return false;
    return true;
  }

  toDto(): DocumentDto {
    return {
      id: this.meta.id,
      workspaceId: this.meta.workspaceId,
      title: this.meta.title,
      createdBy: this.meta.createdBy,
      createdAt: this.meta.createdAt,
      updatedAt: this.meta.updatedAt,
      excerpt: excerpt(this.text, 160),
    };
  }
}

export type OpOutcome =
  | { readonly status: "applied"; readonly seq: number; readonly changes: TextChange[] }
  | { readonly status: "duplicate" }
  | { readonly status: "rejected"; readonly reason: string };

export interface SequencedOp {
  readonly op: RgaOp;
  readonly seq: number;
}

export type ServerOpsListener = (session: DocSession, ops: readonly SequencedOp[], actorId: string | null) => void;

/**
 * Owns the authoritative server replica of every open document.
 *
 * The server assigns a total order (sequence numbers) to integrated
 * operations, appends them to the op log and periodically compacts the log
 * into a snapshot. Clients join with a snapshot and then receive sequenced
 * operations; they acknowledge sequence numbers so the server can detect
 * quiescence and garbage-collect tombstones safely.
 */
export class DocSessionManager {
  private readonly sessions = new Map<string, DocSession>();
  private readonly listeners = new Set<ServerOpsListener>();
  private readonly lastEditActivity = new Map<string, number>();

  constructor(
    private readonly deps: ServiceDeps,
    private readonly activity: ActivityService,
  ) {
    deps.metrics.docSessions.collect(() => this.sessions.size);
  }

  /** Subscribes to operations generated by the server itself (e.g. restores). */
  onServerOps(listener: ServerOpsListener): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }

  peek(documentId: string): DocSession | undefined {
    return this.sessions.get(documentId);
  }

  /** Returns the open session, loading snapshot + op log on first access. */
  get(documentId: string): DocSession {
    const existing = this.sessions.get(documentId);
    if (existing) return existing;
    const { documents } = this.deps.repos;
    const meta = documents.findById(documentId);
    const state = documents.loadState(documentId);
    if (!meta || !state) throw notFound("document");
    const doc = RgaDocument.fromSnapshot(JSON.parse(state.snapshot), `srv${randomSiteId(9)}`);
    let headSeq = state.snapshotSeq;
    const ops = documents.opsAfter(documentId, state.snapshotSeq);
    for (const stored of ops) {
      const parsed = rgaOpSchema.safeParse(JSON.parse(stored.op));
      if (!parsed.success) {
        this.deps.logger.error("corrupt op in log; skipping", { documentId, seq: stored.seq });
        continue;
      }
      const result = doc.apply(parsed.data as RgaOp);
      if (result.status === "pending") this.deps.logger.error("op log replay left a pending op", { documentId, seq: stored.seq });
      headSeq = stored.seq;
    }
    const session = new DocSession(meta, doc, Math.max(headSeq, state.headSeq), state.snapshotSeq, this.deps.clock.now());
    session.opsSinceSnapshot = ops.length;
    this.sessions.set(documentId, session);
    this.deps.logger.debug("document loaded", { documentId, replayed: ops.length, length: doc.length });
    return session;
  }

  join(documentId: string, connectionId: string, userId: string): { session: DocSession; participant: Participant } {
    const session = this.get(documentId);
    const participant: Participant = { connectionId, userId, site: `c${randomSiteId(11)}`, ackSeq: session.headSeq };
    session.participants.set(connectionId, participant);
    session.lastTouched = this.deps.clock.now();
    return { session, participant };
  }

  leave(documentId: string, connectionId: string): void {
    const session = this.sessions.get(documentId);
    if (!session) return;
    session.participants.delete(connectionId);
    session.lastTouched = this.deps.clock.now();
  }

  ack(documentId: string, connectionId: string, seq: number): void {
    const p = this.sessions.get(documentId)?.participants.get(connectionId);
    if (p && seq > p.ackSeq) p.ackSeq = Math.min(seq, this.sessions.get(documentId)?.headSeq ?? seq);
  }

  applyClientOp(documentId: string, connectionId: string, op: RgaOp): OpOutcome {
    const session = this.sessions.get(documentId);
    const participant = session?.participants.get(connectionId);
    if (!session || !participant) return this.reject("not_joined");
    if (op.site !== participant.site) return this.reject("site_mismatch");
    if (session.doc.hasSeen(op.site, op.seq)) return { status: "duplicate" };
    // A client can only have seen clocks the server already has, so a larger
    // clock is either a bug or an attempt to exhaust the clock space.
    if (op.clock > session.doc.lamport + 1) return this.reject("clock_ahead");
    if (!session.doc.canApply(op)) return this.reject("missing_dependencies");
    if (op.kind === "insert" && session.doc.length + op.text.length > MAX_DOCUMENT_LENGTH) return this.reject("document_too_large");
    const result = session.doc.apply(op);
    const seq = ++session.headSeq;
    this.deps.repos.documents.appendOp(documentId, seq, participant.userId, JSON.stringify(op), iso(this.deps.clock.now()));
    this.deps.metrics.docOps.inc({ kind: op.kind });
    this.afterChange(session, participant.userId);
    return { status: "applied", seq, changes: result.changes };
  }

  /**
   * Replaces the document text with `text` using server-generated operations
   * (line diff first, so untouched regions keep their identity). Connected
   * clients receive the operations like any other edit.
   */
  replaceText(documentId: string, text: string, actorId: string | null): SequencedOp[] {
    const session = this.get(documentId);
    const at = iso(this.deps.clock.now());
    const produced: SequencedOp[] = [];
    this.deps.db.transaction(() => {
      for (const splice of diffLines(session.text, text)) {
        for (const op of session.doc.splice(splice.index, splice.deleteCount, splice.insertText)) {
          const seq = ++session.headSeq;
          this.deps.repos.documents.appendOp(documentId, seq, actorId, JSON.stringify(op), at);
          produced.push({ op, seq });
        }
      }
    });
    if (produced.length > 0) {
      this.deps.metrics.docOps.inc({ kind: "server" }, produced.length);
      this.afterChange(session, null);
      for (const listener of this.listeners) listener(session, produced, actorId);
    }
    return produced;
  }

  currentText(documentId: string): { text: string; headSeq: number } {
    const session = this.sessions.get(documentId);
    if (session) return { text: session.text, headSeq: session.headSeq };
    const doc = this.deps.repos.documents.findById(documentId);
    const state = this.deps.repos.documents.loadState(documentId);
    if (!doc || !state) throw notFound("document");
    // Stored content can lag the op log if the process stopped before a
    // flush, so replay when operations exist beyond the snapshot.
    if (state.headSeq > state.snapshotSeq) {
      const loaded = this.get(documentId);
      return { text: loaded.text, headSeq: loaded.headSeq };
    }
    return { text: doc.content, headSeq: state.headSeq };
  }

  setTitle(documentId: string, title: string, updatedAt: string): void {
    const session = this.sessions.get(documentId);
    if (session) session.meta = { ...session.meta, title, updatedAt };
  }

  /** Writes a snapshot (collecting tombstones when quiescent) and trims the op log. */
  compact(session: DocSession): { collected: number; trimmed: number } {
    let collected = 0;
    if (session.isQuiescent()) {
      collected = session.doc.collectGarbage(this.deps.repos.comments.anchorKeys(session.id));
      if (collected > 0) this.deps.metrics.tombstonesCollected.inc(undefined, collected);
    }
    if (session.headSeq === session.snapshotSeq && collected === 0) return { collected, trimmed: 0 };
    const trimmed = this.deps.repos.documents.saveSnapshot(
      session.id,
      JSON.stringify(session.doc.snapshot()),
      session.headSeq,
      session.text,
      iso(this.deps.clock.now()),
    );
    session.snapshotSeq = session.headSeq;
    session.opsSinceSnapshot = 0;
    session.contentDirty = false;
    this.deps.metrics.docSnapshots.inc();
    this.deps.logger.debug("document compacted", { documentId: session.id, seq: session.headSeq, collected, trimmed });
    return { collected, trimmed };
  }

  /** Flushes and unloads sessions that have had no participants for a while. */
  evictIdle(): number {
    const now = this.deps.clock.now();
    let evicted = 0;
    for (const session of [...this.sessions.values()]) {
      if (session.participants.size > 0 || now - session.lastTouched < this.deps.config.documents.idleEvictMs) continue;
      this.unload(session);
      evicted++;
    }
    return evicted;
  }

  /** Forgets a deleted document without writing anything back. */
  drop(documentId: string): DocSession | undefined {
    const session = this.sessions.get(documentId);
    if (!session) return undefined;
    if (session.flushTimer) clearTimeout(session.flushTimer);
    this.sessions.delete(documentId);
    return session;
  }

  flushAll(): void {
    for (const session of this.sessions.values()) {
      if (session.flushTimer) clearTimeout(session.flushTimer);
      session.flushTimer = null;
      if (session.contentDirty) this.flushContent(session);
      this.compact(session);
    }
  }

  close(): void {
    this.flushAll();
    this.sessions.clear();
  }

  stats(): { sessions: number; participants: number } {
    let participants = 0;
    for (const s of this.sessions.values()) participants += s.participants.size;
    return { sessions: this.sessions.size, participants };
  }

  private unload(session: DocSession): void {
    if (session.flushTimer) clearTimeout(session.flushTimer);
    if (session.contentDirty) this.flushContent(session);
    this.compact(session);
    this.sessions.delete(session.id);
  }

  private reject(reason: string): OpOutcome {
    this.deps.metrics.docOpsRejected.inc({ reason });
    return { status: "rejected", reason };
  }

  private afterChange(session: DocSession, userId: string | null): void {
    const now = this.deps.clock.now();
    session.lastTouched = now;
    session.opsSinceSnapshot++;
    session.contentDirty = true;
    session.meta = { ...session.meta, updatedAt: iso(now) };
    if (!session.flushTimer) {
      session.flushTimer = setTimeout(() => {
        session.flushTimer = null;
        if (this.sessions.get(session.id) === session) this.flushContent(session);
      }, this.deps.config.documents.contentFlushMs);
      session.flushTimer.unref();
    }
    if (session.opsSinceSnapshot >= this.deps.config.documents.snapshotEveryOps) this.compact(session);
    if (userId) this.recordEdit(session, userId, now);
  }

  private flushContent(session: DocSession): void {
    const content = session.text;
    this.deps.repos.documents.updateContent(session.id, content);
    session.contentDirty = false;
    this.deps.events.emit({
      type: "document.content",
      documentId: session.id,
      workspaceId: session.workspaceId,
      title: session.meta.title,
      content,
    });
    this.deps.events.emit({ type: "document.upserted", document: session.toDto() });
  }

  /** Records at most one "edited" activity per user and document per window. */
  private recordEdit(session: DocSession, userId: string, now: number): void {
    const key = `${session.id}:${userId}`;
    const last = this.lastEditActivity.get(key);
    if (last !== undefined && now - last < this.deps.config.documents.editActivityWindowMs) return;
    this.lastEditActivity.set(key, now);
    this.activity.record({
      workspaceId: session.workspaceId,
      documentId: session.id,
      actorId: userId,
      verb: "document.edited",
      targetType: "document",
      targetId: session.id,
      meta: { title: session.meta.title },
    });
  }
}
